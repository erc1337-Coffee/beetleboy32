# Converts assets/*.png into LVGL image descriptors in src/assets/ (generated, gitignored).
# Runs as a PlatformIO pre-build script; also runnable directly: python3 scripts/assets.py
#
# Images are stored pre-converted to the display's pixel format, so the device never decodes PNGs.
# Opaque images become RGB565; images with any transparency become RGB565A8.
# Each file becomes `img_<name>` (e.g. assets/day.png -> img_day), declared in src/assets/assets.h.
# Numbered files (<name>_00.png, <name>_01.png...) also get an array: img_<name>_frames[] and
# IMG_<NAME>_FRAME_COUNT, for animations (see scripts/gif_frames.sh).
#
# Files in assets/web/ (served by the setup page) are embedded as raw bytes: assets/web/portal_bg.jpg
# -> web_portal_bg_jpg[] and web_portal_bg_jpg_size, declared in src/assets/web_assets.h.
# portal_bg.jpg: sips -s format jpeg -s formatOptions 60 -Z 720 assets/source/rwo_blue_screen.png
#
# Files in assets/item_icons/ (downloaded by scripts/item_icons.py) are embedded as PNG bytes in a
# table sorted by their site path: assets/item_icons/junk/juicebox.png ->
# "/api/beetle/images/icons/junk/juicebox.png", in src/assets/item_icons.c (see item_icons.h).

import os
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) if "__file__" in globals() else os.getcwd()
SRC_DIR = os.path.join(ROOT, "assets")
OUT_DIR = os.path.join(ROOT, "src", "assets")
WEB = "web_assets"  # output name for assets/web/
ICONS = "item_icons"  # output name for assets/item_icons/
ICON_URL_PREFIX = "/api/beetle/images/icons/"
HEADER = "// Generated by scripts/assets.py from assets/{name}. Do not edit.\n"


def read_png(path):
    """Minimal PNG decoder: 8-bit, non-interlaced, any color type. Returns (w, h, [(r, g, b, a)])."""
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos, idat, palette, trns = 8, b"", None, None
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", chunk)
        elif kind == b"PLTE":
            palette = chunk
        elif kind == b"tRNS":
            trns = chunk
        elif kind == b"IDAT":
            idat += chunk
        elif kind == b"IEND":
            break
    if depth != 8 or interlace:
        raise ValueError("only 8-bit, non-interlaced PNGs are supported (re-export it)")
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[color]

    raw = zlib.decompress(idat)
    stride = w * channels
    prev = bytearray(stride)
    pixels = []
    i = 0
    for _ in range(h):
        ftype = raw[i]
        line = bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - channels] if x >= channels else 0
            b = prev[x]
            c = prev[x - channels] if x >= channels else 0
            if ftype == 1:
                line[x] = (line[x] + a) & 0xFF
            elif ftype == 2:
                line[x] = (line[x] + b) & 0xFF
            elif ftype == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 0xFF
        prev = line
        for x in range(0, stride, channels):
            px = line[x:x + channels]
            if color == 0:
                pixels.append((px[0], px[0], px[0], 255))
            elif color == 2:
                pixels.append((px[0], px[1], px[2], 255))
            elif color == 3:
                idx = px[0]
                alpha = trns[idx] if trns and idx < len(trns) else 255
                pixels.append((palette[idx * 3], palette[idx * 3 + 1], palette[idx * 3 + 2], alpha))
            elif color == 4:
                pixels.append((px[0], px[0], px[0], px[1]))
            else:
                pixels.append((px[0], px[1], px[2], px[3]))
    return w, h, pixels


def to_c(name, w, h, pixels):
    has_alpha = any(p[3] != 255 for p in pixels)
    data = bytearray()
    for r, g, b, _ in pixels:
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += struct.pack("<H", v)
    if has_alpha:
        data += bytes(p[3] for p in pixels)  # RGB565A8: alpha plane follows the color plane
    cf = "LV_COLOR_FORMAT_RGB565A8" if has_alpha else "LV_COLOR_FORMAT_RGB565"

    rows = ",\n".join(
        "  " + ", ".join("0x%02x" % b for b in data[i:i + 24]) for i in range(0, len(data), 24))
    sym = "img_" + name
    return (
        HEADER.format(name=name + ".png")
        + "#include <lvgl.h>\n\n"
        + "static const uint8_t %s_data[] __attribute__((aligned(4))) = {\n%s\n};\n\n" % (sym, rows)
        + "const lv_image_dsc_t %s = {\n" % sym
        + "    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = %s, .flags = 0, .w = %d, .h = %d, .stride = %d},\n"
        % (cf, w, h, w * 2)
        + "    .data_size = sizeof(%s_data),\n" % sym
        + "    .data = %s_data,\n" % sym
        + "};\n")


def byte_rows(data):
    return ",\n".join("  " + ", ".join("0x%02x" % b for b in data[i:i + 24]) for i in range(0, len(data), 24))


def write_web_assets():
    web_dir = os.path.join(SRC_DIR, "web")
    files = sorted(os.listdir(web_dir)) if os.path.isdir(web_dir) else []
    syms = [("web_" + "".join(c if c.isalnum() else "_" for c in f.lower()), f) for f in files if not f.startswith(".")]
    source = HEADER.format(name="web/") + "#include <stddef.h>\n#include <stdint.h>\n"
    for sym, f in syms:
        data = open(os.path.join(web_dir, f), "rb").read()
        source += "\nconst uint8_t %s[] = {\n%s\n};\nconst size_t %s_size = sizeof(%s);\n" % (
            sym, byte_rows(data), sym, sym)
    header = ("#pragma once\n\n// Generated by scripts/assets.py from assets/web/. Do not edit.\n\n"
              "#include <stddef.h>\n#include <stdint.h>\n\n"
              + "".join("extern const uint8_t %s[];\nextern const size_t %s_size;\n" % (s, s) for s, _ in syms))
    if write_if_changed(os.path.join(OUT_DIR, WEB + ".c"), source):
        print("assets: assets/web/ -> src/assets/%s.c (%d files)" % (WEB, len(syms)))
    write_if_changed(os.path.join(OUT_DIR, WEB + ".h"), header)


def write_item_icons():
    icon_dir = os.path.join(SRC_DIR, ICONS)
    files = []
    for dirpath, _, names in os.walk(icon_dir):
        for f in names:
            if f.lower().endswith(".png"):
                rel = os.path.relpath(os.path.join(dirpath, f), icon_dir).replace(os.sep, "/")
                files.append((ICON_URL_PREFIX + rel, os.path.join(dirpath, f)))
    files.sort()
    source = (HEADER.format(name=ICONS + "/") + '#include "item_icons.h"\n')
    for i, (_, path) in enumerate(files):
        source += "\nstatic const uint8_t icon_%d[] = {\n%s\n};\n" % (i, byte_rows(open(path, "rb").read()))
    source += "\nconst BundledIcon bundled_item_icons[] = {\n%s};\nconst size_t bundled_item_icon_count = %d;\n" % (
        "".join('  {"%s", icon_%d, sizeof(icon_%d)},\n' % (url, i, i) for i, (url, _) in enumerate(files)), len(files))
    if not files:
        source = source.replace("const BundledIcon bundled_item_icons[] = {\n};", "const BundledIcon bundled_item_icons[] = {{0, 0, 0}};")
    header = ("#pragma once\n\n// Generated by scripts/assets.py from assets/%s/. Do not edit.\n\n"
              "#include <stddef.h>\n#include <stdint.h>\n\n"
              "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
              "typedef struct {\n  const char *path;  // as the site gives it, e.g. %sjunk/juicebox.png\n"
              "  const uint8_t *png;\n  size_t size;\n} BundledIcon;\n\n"
              "extern const BundledIcon bundled_item_icons[];  // sorted by path\n"
              "extern const size_t bundled_item_icon_count;\n\n"
              "#ifdef __cplusplus\n}\n#endif\n") % (ICONS, ICON_URL_PREFIX)
    write_if_changed(os.path.join(OUT_DIR, ICONS + ".h"), header)
    if write_if_changed(os.path.join(OUT_DIR, ICONS + ".c"), source):
        print("assets: assets/%s/ -> src/assets/%s.c (%d icons)" % (ICONS, ICONS, len(files)))


def write_if_changed(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return False
    with open(path, "w") as f:
        f.write(text)
    return True


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    names = sorted(f[:-4] for f in os.listdir(SRC_DIR) if f.lower().endswith(".png")) if os.path.isdir(SRC_DIR) else []
    for name in names:
        if not name.replace("_", "").isalnum() or not name[0].isalpha() or name != name.lower():
            sys.exit("assets/%s.png: use lowercase letters, digits and _ (it becomes a C symbol)" % name)

    script_mtime = os.path.getmtime(os.path.abspath(__file__)) if "__file__" in globals() else 0
    for name in names:
        src = os.path.join(SRC_DIR, name + ".png")
        out = os.path.join(OUT_DIR, name + ".c")
        if os.path.exists(out) and os.path.getmtime(out) >= max(os.path.getmtime(src), script_mtime):
            continue
        try:
            w, h, pixels = read_png(src)
        except Exception as e:
            sys.exit("assets/%s.png: %s" % (name, e))
        write_if_changed(out, to_c(name, w, h, pixels))
        print("assets: %s.png -> src/assets/%s.c (%dx%d)" % (name, name, w, h))

    for f in os.listdir(OUT_DIR):  # drop outputs whose PNG was deleted
        if f.endswith(".c") and f[:-2] not in names and f[:-2] not in (WEB, ICONS):
            os.remove(os.path.join(OUT_DIR, f))

    sequences = {}
    for n in names:
        base, _, num = n.rpartition("_")
        if base and len(num) == 2 and num.isdigit():
            sequences.setdefault(base, []).append(n)
    header = (
        "#pragma once\n\n// Generated by scripts/assets.py from assets/*.png. Do not edit.\n\n#include <lvgl.h>\n\n"
        + "".join("LV_IMAGE_DECLARE(img_%s);\n" % n for n in names)
        + "".join(
            "\n#define IMG_%s_FRAME_COUNT %d\nstatic const void *img_%s_frames[] = {%s};\n"
            % (base.upper(), len(frames), base, ", ".join("&img_" + f for f in frames))
            for base, frames in sorted(sequences.items())))
    write_if_changed(os.path.join(OUT_DIR, "assets.h"), header)
    write_web_assets()
    write_item_icons()


if __name__ == "__main__":
    main()
else:  # PlatformIO pre-script
    Import("env")  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
    SRC_DIR = os.path.join(ROOT, "assets")
    OUT_DIR = os.path.join(ROOT, "src", "assets")
    main()
